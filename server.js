function maskNumbers(text) { return String(text || '').replace(/\d/g, '.'); }
function escapeRegex(s) { return String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

function poissonPmf(k, lambda) {
  let fact = 1;
  for (let i = 2; i <= k; i++) fact *= i;
  return Math.exp(-lambda) * Math.pow(lambda, k) / fact;
}
function poissonOver(line, lambda) {
  const k = Math.floor(line);
  let p = 0;
  for (let i = 0; i <= k; i++) p += poissonPmf(i, lambda);
  return Math.max(0, Math.min(1, 1 - p));
}
function bucketConfidence(p) {
  const d = Math.abs(p - 0.5) * 2;
  if (d >= 0.5) return 'high';
  if (d >= 0.25) return 'medium';
  return 'low';
}

// Team name normalization for bookmaker matching
function normalizeTeamName(name) {
  return String(name || '')
    .toLowerCase()
    .replace(/\b(fc|cf|sc|afc|united|utd|city|club|de|the|ac|as|ss|ssc|sv|vfl|vfb|tsg|bsc)\b/g, '')
    .replace(/[^a-z0-9 ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function slugify(str) {
  return normalizeTeamName(str).replace(/\s+/g, '-');
}

