async function getPerformanceStats() {
  const [totalPreds, settledPreds] = await Promise.all([
    PredictionLog.countDocuments(),
    PredictionLog.countDocuments({ settledAt: { $ne: null } }),
  ]);
  const settled = await PredictionLog.find({ settledAt: { $ne: null } }).lean();

  const pct = (arr, k) => arr.length ? arr.filter(x => x[k]).length / arr.length : 0;
  const filterField = (k) => settled.filter(p => p[k] !== null && p[k] !== undefined);

  const bttsF = filterField('bttsCorrect');
  const o15F = filterField('over15Correct');
  const o25F = filterField('over25Correct');
  const o35F = filterField('over35Correct');
  const hF = filterField('halfCorrect');

  const rolling = await RollingStats.findOne().sort({ timestamp: -1 }).lean();
  const allTickets = await Ticket.find({ status: { $in: ['won', 'lost'] } }).lean();
  const wonTickets = allTickets.filter(t => t.status === 'won').length;
  const ticketWinRate = allTickets.length ? wonTickets / allTickets.length : 0;

  return {
    totalPredictions: totalPreds,
    settledPredictions: settledPreds,
    bttsAccuracy: +(pct(bttsF, 'bttsCorrect') * 100).toFixed(1),
    over15Accuracy: +(pct(o15F, 'over15Correct') * 100).toFixed(1),
    over25Accuracy: +(pct(o25F, 'over25Correct') * 100).toFixed(1),
    over35Accuracy: +(pct(o35F, 'over35Correct') * 100).toFixed(1),
    halfAccuracy: +(pct(hF, 'halfCorrect') * 100).toFixed(1),
    ticketWinRate: +(ticketWinRate * 100).toFixed(1),
    totalTicketsSettled: allTickets.length,
    rolling: rolling || null,
  };
}

