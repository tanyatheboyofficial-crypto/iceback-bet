async function logPrediction(pred) {
  if (!pred.prediction) return;
  try {
    await PredictionLog.updateOne(
      { eventId: pred.eventId },
      {
        $setOnInsert: {
          eventId: pred.eventId,
          homeTeamId: pred.homeTeam.id, awayTeamId: pred.awayTeam.id,
          homeTeam: pred.homeTeam.name, awayTeam: pred.awayTeam.name,
          league: pred.league, leagueId: pred.leagueId,
          kickoff: new Date(pred.kickoff),
          ourBttsPick: pred.prediction.btts.pick, ourBttsProb: pred.prediction.btts.prob,
          ourOver15Pick: pred.prediction.over15.pick, ourOver15Prob: pred.prediction.over15.prob,
          ourOver25Pick: pred.prediction.over25.pick, ourOver25Prob: pred.prediction.over25.prob,
          ourOver35Pick: pred.prediction.over35.pick, ourOver35Prob: pred.prediction.over35.prob,
          ourHighestHalf: pred.prediction.highestHalf.pick,
          ourExpectedGoals: pred.prediction.expectedGoals.total,
          ourConfidence: pred.prediction.confidence,
          ourBttsOdds: pred.markets?.btts?.odds,
          ourOver25Odds: pred.markets?.overUnder25?.odds,
        },
      },
      { upsert: true }
    );
  } catch (e) { /* silent */ }
}

async function settlePredictions() {
  try {
    const cutoff = new Date(Date.now() - 3 * 3600000);
    const pending = await PredictionLog.find({ settledAt: null, kickoff: { $lt: cutoff } }).limit(50);
    if (!pending.length) return { settled: 0 };

    let settled = 0;
    for (const log of pending) {
      try {
        const data = await bzGet(`/events/${log.eventId}/`);
        if (!data || data.status !== 'finished') continue;
        const hg = Number(data.home_score ?? 0);
        const ag = Number(data.away_score ?? 0);
        const hgHt = Number(data.home_score_ht ?? 0);
        const agHt = Number(data.away_score_ht ?? 0);
        const total = hg + ag;
        const bttsHit = hg > 0 && ag > 0;
        const h1 = hgHt + agHt;
        const h2 = total - h1;
        const actualHalf = h2 > h1 ? '2H' : h2 < h1 ? '1H' : 'Equal';

        log.actualHomeScore = hg; log.actualAwayScore = ag;
        log.actualOutcome = hg > ag ? 'Home Win' : hg < ag ? 'Away Win' : 'Draw';
        log.totalGoals = total; log.btts = bttsHit;
        log.actual1H = h1; log.actual2H = h2; log.actualHighestHalf = actualHalf;

        log.bttsCorrect = log.ourBttsPick ? (log.ourBttsPick === 'Yes' ? bttsHit : !bttsHit) : null;
        log.over15Correct = log.ourOver15Pick ? (log.ourOver15Pick === 'Over 1.5' ? total > 1.5 : total < 1.5) : null;
        log.over25Correct = log.ourOver25Pick ? (log.ourOver25Pick === 'Over 2.5' ? total > 2.5 : total < 2.5) : null;
        log.over35Correct = log.ourOver35Pick ? (log.ourOver35Pick === 'Over 3.5' ? total > 3.5 : total < 3.5) : null;
        log.halfCorrect = log.ourHighestHalf ? (log.ourHighestHalf === actualHalf) : null;
        log.settledAt = new Date();
        await log.save();
        settled++;

        if (log.leagueId) {
          await LeagueKnowledge.updateOne(
            { leagueId: log.leagueId },
            {
              $setOnInsert: { leagueName: log.league },
              $inc: {
                totalMatches: 1, totalGoals: total,
                over15Hits: total > 1.5 ? 1 : 0,
                over25Hits: total > 2.5 ? 1 : 0,
                over35Hits: total > 3.5 ? 1 : 0,
                bttsHits: bttsHit ? 1 : 0,
                homeWins: hg > ag ? 1 : 0,
                draws: hg === ag ? 1 : 0,
                awayWins: ag > hg ? 1 : 0,
              },
              $set: { lastUpdated: new Date() },
            },
            { upsert: true }
          );
        }

        await updateTeamHistoryOnSettle(data);

        await FeatureSnapshot.updateOne(
          { eventId: log.eventId, market: 'over25' },
          { $set: { settledAt: new Date(), actual: total > 2.5 ? 'Over 2.5' : 'Under 2.5', correct: log.over25Correct } }
        );
        await FeatureSnapshot.updateOne(
          { eventId: log.eventId, market: 'btts' },
          { $set: { settledAt: new Date(), actual: bttsHit ? 'Yes' : 'No', correct: log.bttsCorrect } }
        );
        await FeatureSnapshot.updateOne(
          { eventId: log.eventId, market: 'over15' },
          { $set: { settledAt: new Date(), actual: total > 1.5 ? 'Over 1.5' : 'Under 1.5', correct: log.over15Correct } }
        );
      } catch (e) { /* silent */ }
    }

    if (settled) console.log(`[Knowledge] Settled ${settled} predictions`);
    return { settled };
  } catch (e) {
    console.warn('[Knowledge] Settle error:', e.message);
    return { settled: 0 };
  }
}

async function fetchUpcomingMatches(limit = 60, leagueId = null) {
  if (!BZZOIRO_PREDICTIONS.length) await preloadBzzoiroFixtures();
  if (!BZZOIRO_PREDICTIONS.length) return [];

  const now = Date.now();
  let upcoming = BZZOIRO_PREDICTIONS
    .filter(p => new Date(p.kickoff).getTime() > now - 2 * 3600000)
    .sort((a, b) => new Date(a.kickoff) - new Date(b.kickoff));

  if (leagueId) upcoming = upcoming.filter(p => p.leagueId === Number(leagueId));
  return upcoming.slice(0, limit);
}

