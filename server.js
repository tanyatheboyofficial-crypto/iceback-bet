function parseOddsEvent(ev) {
  // Pick the sharpest bookmaker available (Pinnacle > Betfair > first)
  const preferred = ['pinnacle', 'betfair_ex_eu', 'betfair', 'bet365', 'williamhill'];
  let book = null;
  for (const name of preferred) {
    book = (ev.bookmakers || []).find(b => b.key === name);
    if (book) break;
  }
  if (!book) book = ev.bookmakers?.[0];
  if (!book) return null;

  const markets = {};
  for (const m of book.markets || []) {
    if (m.key === 'h2h') {
      const home = m.outcomes.find(o => o.name === ev.home_team)?.price;
      const away = m.outcomes.find(o => o.name === ev.away_team)?.price;
      const draw = m.outcomes.find(o => o.name === 'Draw')?.price;
      markets.h2h = { home, draw, away };
    }
    if (m.key === 'btts') {
      markets.btts = {
        yes: m.outcomes.find(o => o.name === 'Yes')?.price,
        no: m.outcomes.find(o => o.name === 'No')?.price,
      };
    }
    if (m.key === 'totals') {
      const over15 = m.outcomes.find(o => o.name === 'Over' && o.point === 1.5);
      const under15 = m.outcomes.find(o => o.name === 'Under' && o.point === 1.5);
      const over25 = m.outcomes.find(o => o.name === 'Over' && o.point === 2.5);
      const under25 = m.outcomes.find(o => o.name === 'Under' && o.point === 2.5);
      const over35 = m.outcomes.find(o => o.name === 'Over' && o.point === 3.5);
      const under35 = m.outcomes.find(o => o.name === 'Under' && o.point === 3.5);
      if (over15 || under15) markets.overUnder15 = { over: over15?.price, under: under15?.price };
      if (over25 || under25) markets.overUnder25 = { over: over25?.price, under: under25?.price };
      if (over35 || under35) markets.overUnder35 = { over: over35?.price, under: under35?.price };
    }
  }

  return {
    eventKey: `${slugify(ev.home_team)}|${slugify(ev.away_team)}|${dayKey(ev.commence_time)}`,
    homeTeam: ev.home_team,
    awayTeam: ev.away_team,
    kickoff: new Date(ev.commence_time),
    league: ev.sport_title,
    bookmaker: book.key,
    bookmakerTitle: book.title,
    markets,
    lastUpdated: new Date(),
  };
}

async function refreshBookmakerOdds() {
  if (!ODDS_API_KEY) {
    console.log('[Odds] No THE_ODDS_API_KEY — skipping');
    return;
  }
  console.log('[Odds] Refreshing bookmaker odds...');
  let total = 0;

  for (const sport of ODDS_SPORTS) {
    const events = await fetchOddsForSport(sport);
    for (const ev of events) {
      const parsed = parseOddsEvent(ev);
      if (!parsed) continue;

      // Try to match against a bzzoiro event for eventId linking
      const match = BZZOIRO_PREDICTIONS.find(p =>
        slugify(p.homeTeam.name) === slugify(parsed.homeTeam) &&
        slugify(p.awayTeam.name) === slugify(parsed.awayTeam) &&
        Math.abs(new Date(p.kickoff).getTime() - parsed.kickoff.getTime()) < 6 * 3600000
      );

      await BookmakerOdds.updateOne(
        { eventKey: parsed.eventKey },
        {
          $set: {
            ...parsed,
            eventId: match?.eventId || null,
          },
        },
        { upsert: true }
      );
      total++;
    }
    await new Promise(r => setTimeout(r, 500));
  }
  console.log(`[Odds] Refreshed ${total} events`);
}

async function getBookmakerOddsFor(pred) {
  // First try by eventId (fast)
  if (pred.eventId) {
    const byId = await BookmakerOdds.findOne({ eventId: pred.eventId }).lean();
    if (byId) return byId;
  }
  // Fallback: match by team names + day
  const home = slugify(pred.homeTeam.name);
  const away = slugify(pred.awayTeam.name);
  const day = dayKey(pred.kickoff);
  const all = await BookmakerOdds.find().lean();
  for (const b of all) {
    const k = b.eventKey.split('|');
    if (k[0] === home && k[1] === away && k[2] === day) return b;
  }
  return null;
}

