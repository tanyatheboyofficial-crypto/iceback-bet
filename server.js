function normalizeBzzoiroPrediction(p) {
  const ev = p.event || {};
  const mk = p.markets || {};
  const mr = mk.match_result || {};
  const eg = mk.expected_goals || {};
  const ou = mk.over_under || {};
  const btts = mk.btts || {};
  const model = p.model || {};

  const homeId = ev.home_team_id;
  const awayId = ev.away_team_id;
  const conf = Number(model.confidence || 0);

  const impliedHome = mr.prob_home ? Number((100 / mr.prob_home).toFixed(2)) : null;
  const impliedDraw = mr.prob_draw ? Number((100 / mr.prob_draw).toFixed(2)) : null;
  const impliedAway = mr.prob_away ? Number((100 / mr.prob_away).toFixed(2)) : null;

  const overUnder25 = typeof ou.prob_over_25 === 'number'
    ? (() => {
        const isOver = ou.prob_over_25 >= 50;
        return { pick: isOver ? 'Over 2.5' : 'Under 2.5',
          probability: Math.round(isOver ? ou.prob_over_25 : 100 - ou.prob_over_25),
          odds: Number((isOver ? 100 / ou.prob_over_25 : 100 / (100 - ou.prob_over_25)).toFixed(2)) };
      })() : null;

  const overUnder15 = typeof ou.prob_over_15 === 'number'
    ? (() => {
        const isOver = ou.prob_over_15 >= 50;
        return { pick: isOver ? 'Over 1.5' : 'Under 1.5',
          probability: Math.round(isOver ? ou.prob_over_15 : 100 - ou.prob_over_15),
          odds: Number((isOver ? 100 / ou.prob_over_15 : 100 / (100 - ou.prob_over_15)).toFixed(2)) };
      })() : null;

  const overUnder35 = typeof ou.prob_over_35 === 'number'
    ? (() => {
        const isOver = ou.prob_over_35 >= 50;
        return { pick: isOver ? 'Over 3.5' : 'Under 3.5',
          probability: Math.round(isOver ? ou.prob_over_35 : 100 - ou.prob_over_35),
          odds: Number((isOver ? 100 / ou.prob_over_35 : 100 / (100 - ou.prob_over_35)).toFixed(2)) };
      })() : null;

  const bttsMarket = typeof btts.prob_yes === 'number'
    ? (() => {
        const isYes = btts.prob_yes >= 50;
        return { pick: isYes ? 'Yes' : 'No',
          probability: Math.round(isYes ? btts.prob_yes : 100 - btts.prob_yes),
          odds: Number((isYes ? 100 / btts.prob_yes : 100 / (100 - btts.prob_yes)).toFixed(2)) };
      })() : null;

  return {
    id: 'bz_' + (p.id || ev.id || Math.random().toString(36).slice(2)),
    eventId: ev.id,
    kickoff: ev.event_date || new Date().toISOString(),
    status: ev.status || 'notstarted',
    league: ev.league_name || 'Football',
    leagueId: ev.league_id,
    homeTeam: { id: homeId, name: ev.home_team || 'Home', logo: homeId ? `${BZZOIRO_IMG}/${homeId}/` : '' },
    awayTeam: { id: awayId, name: ev.away_team || 'Away', logo: awayId ? `${BZZOIRO_IMG}/${awayId}/` : '' },
    probabilities: { home: mr.prob_home, draw: mr.prob_draw, away: mr.prob_away },
    odds: {
      home: impliedHome, draw: impliedDraw, away: impliedAway,
      over25: overUnder25?.odds || null,
      bttsYes: bttsMarket?.odds || null,
      source: 'bzzoiro_implied',
    },
    markets: { overUnder15, overUnder25, overUnder35, btts: bttsMarket, highestHalf: null },
    expectedGoals: eg.home != null && eg.away != null ? Number((eg.home + eg.away).toFixed(2)) : null,
    expectedHomeGoals: eg.home,
    expectedAwayGoals: eg.away,
    mostLikelyScore: mk.score?.most_likely || null,
    model: { version: model.version || 'bzzoiro', confidence: conf },
  };
}

