const ENRICH_CACHE = new Map();
const ENRICH_TTL = 5 * 60 * 1000;

let RULES_CACHE = null, RULES_CACHE_AT = 0;
let RULE_PERF_CACHE = null, RULE_PERF_AT = 0;
let CALIB_CACHE = null, CALIB_AT = 0;
let META_CACHE = null, META_AT = 0;
const CACHE_TTL = 5 * 60 * 1000;

const apiCache = new Map();
function cacheGet(k) {
  const e = apiCache.get(k);
  if (!e) return null;
  if (Date.now() > e.exp) { apiCache.delete(k); return null; }
  return e.v;
}
function cacheSet(k, v, ttlMs = 60000) {
  if (apiCache.size > 500) {
    const now = Date.now();
    for (const [key, val] of apiCache) if (now > val.exp) apiCache.delete(key);
  }
  apiCache.set(k, { v, exp: Date.now() + ttlMs });
}

async function getCachedRules() {
  if (RULES_CACHE && Date.now() - RULES_CACHE_AT < CACHE_TTL) return RULES_CACHE;
  const rules = await Rule.find({ enabled: true }).lean();
  RULES_CACHE = Object.fromEntries(rules.map(r => [r.key, r.config || {}]));
  RULES_CACHE_AT = Date.now();
  return RULES_CACHE;
}
async function getCachedRulePerf() {
  if (RULE_PERF_CACHE && Date.now() - RULE_PERF_AT < CACHE_TTL) return RULE_PERF_CACHE;
  const perf = await RulePerformance.find({ muted: false }).lean();
  RULE_PERF_CACHE = Object.fromEntries(perf.map(p => [p.ruleKey, p.currentWeight || 1]));
  RULE_PERF_AT = Date.now();
  return RULE_PERF_CACHE;
}
async function getCachedCalibration(market) {
  if (!CALIB_CACHE || Date.now() - CALIB_AT > CACHE_TTL) {
    const all = await Calibration.find().lean();
    CALIB_CACHE = Object.fromEntries(all.map(c => [c.market, c]));
    CALIB_AT = Date.now();
  }
  return CALIB_CACHE[market] || null;
}
async function getCachedMeta(market) {
  if (!META_CACHE || Date.now() - META_AT > CACHE_TTL) {
    const all = await MetaLearner.find().lean();
    META_CACHE = Object.fromEntries(all.map(m => [m.market, m]));
    META_AT = Date.now();
  }
  return META_CACHE[market] || null;
}

function invalidateCaches() {
  RULES_CACHE_AT = 0; RULE_PERF_AT = 0; CALIB_AT = 0; META_AT = 0;
  ENRICH_CACHE.clear();
}

