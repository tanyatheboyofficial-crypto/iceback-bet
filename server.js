async function updateTeamHistoryOnSettle(event) {
  const hg = Number(event.home_score ?? 0);
  const ag = Number(event.away_score ?? 0);
  const hgHt = Number(event.home_score_ht ?? 0);
  const agHt = Number(event.away_score_ht ?? 0);

  for (const side of [
    { id: event.home_team_id, name: event.home_team, gf: hg, ga: ag, hft: hgHt, hta: agHt,
      opp: event.away_team, ho: 'H' },
    { id: event.away_team_id, name: event.away_team, gf: ag, ga: hg, hft: agHt, hta: hgHt,
      opp: event.home_team, ho: 'A' },
  ]) {
    const match = {
      eventId: event.id, date: new Date(event.event_date),
      opponent: side.opp, homeOrAway: side.ho,
      goalsFor: side.gf, goalsAgainst: side.ga,
      result: side.gf > side.ga ? 'W' : side.gf < side.ga ? 'L' : 'D',
      halfTimeFor: side.hft, halfTimeAgainst: side.hta,
    };
    await TeamHistory.updateOne(
      { teamId: side.id },
      {
        $setOnInsert: { teamName: side.name, league: event.league_name, leagueId: event.league_id },
        $push: { matches: { $each: [match], $slice: -20 } },
        $set: { lastUpdated: new Date() },
      },
      { upsert: true }
    );
    const doc = await TeamHistory.findOne({ teamId: side.id });
    if (doc) { aggregateTeamHistory(doc); await doc.save(); }
  }

  const a = event.home_team_id, b = event.away_team_id;
  if (a && b) {
    const pairKey = [a, b].sort((x, y) => x - y).join('_');
    const h2hMatch = {
      date: new Date(event.event_date),
      homeTeam: event.home_team, awayTeam: event.away_team,
      homeScore: hg, awayScore: ag,
      totalGoals: hg + ag, btts: hg > 0 && ag > 0,
      halfTimeScore: `${hgHt}-${agHt}`,
    };
    await H2H.updateOne(
      { pairKey },
      {
        $setOnInsert: { teamAId: Math.min(a, b), teamBId: Math.max(a, b) },
        $push: { matches: { $each: [h2hMatch], $slice: -5 } },
        $set: { lastUpdated: new Date() },
      },
      { upsert: true }
    );
    const h2h = await H2H.findOne({ pairKey });
    if (h2h && h2h.matches.length) {
      const n = h2h.matches.length;
      h2h.avgTotalGoals = +(h2h.matches.reduce((s, x) => s + x.totalGoals, 0) / n).toFixed(2);
      h2h.bttsRate = +(h2h.matches.filter(x => x.btts).length / n).toFixed(3);
      h2h.over25Rate = +(h2h.matches.filter(x => x.totalGoals > 2.5).length / n).toFixed(3);
      await h2h.save();
    }
  }
}

