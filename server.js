function aggregateTeamHistory(team) {
  const m = team.matches || [];
  if (!m.length) return;
  const n = m.length;

  let scored = 0, conceded = 0, btts = 0, over15 = 0, over25 = 0, over35 = 0;
  let cs = 0, fts = 0, g1h = 0, g2h = 0;

  for (const x of m) {
    const gf = Number(x.goalsFor || 0);
    const ga = Number(x.goalsAgainst || 0);
    const total = gf + ga;
    scored += gf; conceded += ga;
    if (gf > 0 && ga > 0) btts++;
    if (total > 1.5) over15++;
    if (total > 2.5) over25++;
    if (total > 3.5) over35++;
    if (ga === 0) cs++;
    if (gf === 0) fts++;
    const h1 = Number(x.halfTimeFor || 0) + Number(x.halfTimeAgainst || 0);
    g1h += h1;
    g2h += Math.max(0, total - h1);
  }

  team.avgScored = +(scored / n).toFixed(2);
  team.avgConceded = +(conceded / n).toFixed(2);
  team.avgCombined = +((scored + conceded) / n).toFixed(2);
  team.bttsRate = +(btts / n).toFixed(3);
  team.over15Rate = +(over15 / n).toFixed(3);
  team.over25Rate = +(over25 / n).toFixed(3);
  team.over35Rate = +(over35 / n).toFixed(3);
  team.cleanSheetRate = +(cs / n).toFixed(3);
  team.failedToScoreRate = +(fts / n).toFixed(3);
  team.goals1H = g1h;
  team.goals2H = g2h;

  const sorted = [...m].sort((a, b) => new Date(b.date) - new Date(a.date));
  if (sorted[0]) {
    team.restDays = Math.floor((Date.now() - new Date(sorted[0].date).getTime()) / 86400000);
  }
  const sevenDaysAgo = Date.now() - 7 * 86400000;
  team.matchesLast7 = m.filter(x => new Date(x.date).getTime() > sevenDaysAgo).length;

  team.lastUpdated = new Date();
}

async function refreshTeamHistory(teamId, teamName, leagueName, leagueId) {
  try {
    const data = await bzGet('/events/', {
      team_id: teamId, status: 'finished', limit: 20, ordering: '-event_date',
    });
    const events = data.results || [];
    const matches = events.map(e => {
      const isHome = e.home_team_id === teamId;
      const gf = isHome ? Number(e.home_score ?? 0) : Number(e.away_score ?? 0);
      const ga = isHome ? Number(e.away_score ?? 0) : Number(e.home_score ?? 0);
      const hft = isHome ? Number(e.home_score_ht ?? 0) : Number(e.away_score_ht ?? 0);
      const hta = isHome ? Number(e.away_score_ht ?? 0) : Number(e.home_score_ht ?? 0);
      return {
        eventId: e.id, date: new Date(e.event_date),
        opponent: isHome ? e.away_team : e.home_team,
        homeOrAway: isHome ? 'H' : 'A',
        goalsFor: gf, goalsAgainst: ga,
        result: gf > ga ? 'W' : gf < ga ? 'L' : 'D',
        halfTimeFor: hft, halfTimeAgainst: hta,
      };
    });

    let doc = await TeamHistory.findOne({ teamId });
    if (!doc) doc = new TeamHistory({ teamId });
    doc.teamName = teamName; doc.league = leagueName; doc.leagueId = leagueId;
    doc.matches = matches;
    aggregateTeamHistory(doc);
    await doc.save();
  } catch (e) { /* silent */ }
}

