// ═══════════════════════════════════════════════════════════
// GOALS PREDICTION ENGINE
// ═══════════════════════════════════════════════════════════
async function computeGoalsPrediction(pred) {
  const cached = ENRICH_CACHE.get(pred.eventId);
  if (cached && Date.now() - cached.enrichedAt < ENRICH_TTL) {
    Object.assign(pred, cached.pred);
    return pred;
  }

  const R = await getCachedRules();
  const ruleMul = await getCachedRulePerf();

  const [homeTH, awayTH, league, h2h, oddsMove, bookOdds] = await Promise.all([
    TeamHistory.findOne({ teamId: pred.homeTeam.id }).lean(),
    TeamHistory.findOne({ teamId: pred.awayTeam.id }).lean(),
    LeagueKnowledge.findOne({ leagueId: pred.leagueId }).lean(),
    H2H.findOne({ pairKey: [pred.homeTeam.id, pred.awayTeam.id].sort((a, b) => a - b).join('_') }).lean(),
    OddsMovement.findOne({ eventId: pred.eventId }).lean(),
    getBookmakerOddsFor(pred),
  ]);

  const hAvgS = homeTH?.avgScored ?? 1.2;
  const hAvgC = homeTH?.avgConceded ?? 1.2;
  const aAvgS = awayTH?.avgScored ?? 1.2;
  const aAvgC = awayTH?.avgConceded ?? 1.2;

  let xgHome = (hAvgS + aAvgC) / 2;
  let xgAway = (aAvgS + hAvgC) / 2;

  if (pred.expectedHomeGoals != null && pred.expectedAwayGoals != null) {
    xgHome = xgHome * 0.55 + Number(pred.expectedHomeGoals) * 0.45;
    xgAway = xgAway * 0.55 + Number(pred.expectedAwayGoals) * 0.45;
  }

  const w1 = (R.g1_team_goals_avg?.weight || 15) * (ruleMul.g1_team_goals_avg || 1);
  const w2 = (R.g2_team_conceded_avg?.weight || 15) * (ruleMul.g2_team_conceded_avg || 1);
  xgHome *= (1 + (w1 - 15) / 200);
  xgAway *= (1 + (w2 - 15) / 200);

  const fatigueThreshold = R.g11_fatigue_goals?.matchesThreshold || 3;
  const fatigueSub = R.g11_fatigue_goals?.expectedGoalsSub || 0.25;
  if ((homeTH?.matchesLast7 || 0) >= fatigueThreshold) xgHome = Math.max(0.2, xgHome - fatigueSub);
  if ((awayTH?.matchesLast7 || 0) >= fatigueThreshold) xgAway = Math.max(0.2, xgAway - fatigueSub);

  if (h2h && h2h.matches.length >= 2) {
    const h2hW = (R.g10_h2h_goals?.weight || 10) / 100;
    const h2hAvg = h2h.avgTotalGoals || (xgHome + xgAway);
    const currentTotal = xgHome + xgAway;
    const blended = currentTotal * (1 - h2hW) + h2hAvg * h2hW;
    const scale = blended / currentTotal;
    xgHome *= scale; xgAway *= scale;
  }

  if (league && league.totalMatches >= 10) {
    const leagueAvg = league.totalGoals / league.totalMatches;
    const leagueW = (R.g9_league_goals_avg?.weight || 10) / 100;
    const current = xgHome + xgAway;
    const blended = current * (1 - leagueW) + leagueAvg * leagueW;
    const scale = blended / current;
    xgHome *= scale; xgAway *= scale;
  }

  const xgTotal = xgHome + xgAway;

  const homeScoresProb = 1 - Math.exp(-xgHome);
  const awayScoresProb = 1 - Math.exp(-xgAway);
  let bttsYesProb = homeScoresProb * awayScoresProb;

  const histBtts = ((homeTH?.bttsRate ?? 0.5) + (awayTH?.bttsRate ?? 0.5)) / 2;
  bttsYesProb = bttsYesProb * 0.6 + histBtts * 0.4;

  const csThreshold = R.g7_clean_sheet_rate?.highRate || 0.4;
  if ((homeTH?.cleanSheetRate || 0) > csThreshold || (awayTH?.cleanSheetRate || 0) > csThreshold) bttsYesProb -= 0.08;
  const ftsThreshold = R.g8_failed_to_score?.highRate || 0.4;
  if ((homeTH?.failedToScoreRate || 0) > ftsThreshold || (awayTH?.failedToScoreRate || 0) > ftsThreshold) bttsYesProb -= 0.08;
  bttsYesProb = Math.max(0.05, Math.min(0.95, bttsYesProb));

  let over15Prob = poissonOver(1.5, xgTotal);
  let over25Prob = poissonOver(2.5, xgTotal);
  let over35Prob = poissonOver(3.5, xgTotal);

  let halfPick = 'Equal', halfConf = 'low';
  if (homeTH && awayTH) {
    const h1 = (homeTH.goals1H || 0) + (awayTH.goals1H || 0);
    const h2 = (homeTH.goals2H || 0) + (awayTH.goals2H || 0);
    const total = h1 + h2;
    if (total > 5) {
      const ratio = h2 / Math.max(1, h1);
      const rT = R.g6_half_goals_split?.ratioThreshold || 1.25;
      const sR = R.g6_half_goals_split?.strongRatio || 1.5;
      if (ratio >= rT) { halfPick = '2H'; halfConf = ratio >= sR ? 'high' : 'medium'; }
      else if (ratio <= 1 / rT) { halfPick = '1H'; halfConf = (1 / ratio) >= sR ? 'high' : 'medium'; }
    }
  }

  const features = buildFeatureVector(pred, homeTH, awayTH, league, h2h);
  const [metaOver25, metaBtts, metaOver15] = await Promise.all([
    metaPredictCached('over25', features),
    metaPredictCached('btts', features),
    metaPredictCached('over15', features),
  ]);
  if (metaOver25 !== null) over25Prob = over25Prob * 0.4 + metaOver25 * 0.6;
  if (metaBtts !== null) bttsYesProb = bttsYesProb * 0.4 + metaBtts * 0.6;
  if (metaOver15 !== null) over15Prob = over15Prob * 0.4 + metaOver15 * 0.6;

  over25Prob = await calibrateProbCached('over25', over25Prob);
  bttsYesProb = await calibrateProbCached('btts', bttsYesProb);
  over15Prob = await calibrateProbCached('over15', over15Prob);

  const overallConf = bucketConfidence(Math.max(over25Prob, bttsYesProb, over15Prob));

  pred.prediction = {
    btts: { pick: bttsYesProb >= 0.5 ? 'Yes' : 'No', prob: +(bttsYesProb * 100).toFixed(1), confidence: bucketConfidence(bttsYesProb) },
    over15: { pick: over15Prob >= 0.5 ? 'Over 1.5' : 'Under 1.5', prob: +(over15Prob * 100).toFixed(1), confidence: bucketConfidence(over15Prob) },
    over25: { pick: over25Prob >= 0.5 ? 'Over 2.5' : 'Under 2.5', prob: +(over25Prob * 100).toFixed(1), confidence: bucketConfidence(over25Prob) },
    over35: { pick: over35Prob >= 0.5 ? 'Over 3.5' : 'Under 3.5', prob: +(over35Prob * 100).toFixed(1), confidence: bucketConfidence(over35Prob) },
    highestHalf: { pick: halfPick, confidence: halfConf },
    expectedGoals: { home: +xgHome.toFixed(2), away: +xgAway.toFixed(2), total: +xgTotal.toFixed(2) },
    confidence: overallConf,
  };

  pred.knowledge = {
    homeHistory: homeTH ? {
      matches: homeTH.matches.length,
      avgScored: homeTH.avgScored, avgConceded: homeTH.avgConceded,
      bttsRate: homeTH.bttsRate, over25Rate: homeTH.over25Rate,
      cleanSheetRate: homeTH.cleanSheetRate, failedToScoreRate: homeTH.failedToScoreRate,
      restDays: homeTH.restDays, matchesLast7: homeTH.matchesLast7,
      goals1H: homeTH.goals1H, goals2H: homeTH.goals2H,
    } : null,
    awayHistory: awayTH ? {
      matches: awayTH.matches.length,
      avgScored: awayTH.avgScored, avgConceded: awayTH.avgConceded,
      bttsRate: awayTH.bttsRate, over25Rate: awayTH.over25Rate,
      cleanSheetRate: awayTH.cleanSheetRate, failedToScoreRate: awayTH.failedToScoreRate,
      restDays: awayTH.restDays, matchesLast7: awayTH.matchesLast7,
      goals1H: awayTH.goals1H, goals2H: awayTH.goals2H,
    } : null,
    h2h: h2h ? { matches: h2h.matches.length, avgTotalGoals: h2h.avgTotalGoals, bttsRate: h2h.bttsRate, over25Rate: h2h.over25Rate } : null,
    leagueOver25Rate: league?.totalMatches >= 5 ? +(league.over25Hits / league.totalMatches).toFixed(3) : null,
    leagueBttsRate: league?.totalMatches >= 5 ? +(league.bttsHits / league.totalMatches).toFixed(3) : null,
    steamMove: oddsMove?.steamMove || false,
    rulesUsed: Object.keys(R),
  };

  const gate = R.g14_publish_gate || { over15: 0.80, over25: 0.66, btts: 0.68, half: 0.72 };
  pred.publishable = {
    over15: over15Prob >= gate.over15,
    over25: over25Prob >= gate.over25,
    btts: bttsYesProb >= gate.btts,
    half: halfConf === 'high',
  };

  // ═══ MERGE BOOKMAKER ODDS + IMPLIED FALLBACK ═══
  const impliedBttsYes = +(100 / pred.prediction.btts.prob).toFixed(2);
  const impliedBttsNo = +(100 / (100 - pred.prediction.btts.prob)).toFixed(2);
  const impliedOver15 = +(100 / pred.prediction.over15.prob).toFixed(2);
  const impliedUnder15 = +(100 / (100 - pred.prediction.over15.prob)).toFixed(2);
  const impliedOver25 = +(100 / pred.prediction.over25.prob).toFixed(2);
  const impliedUnder25 = +(100 / (100 - pred.prediction.over25.prob)).toFixed(2);
  const impliedOver35 = +(100 / pred.prediction.over35.prob).toFixed(2);
  const impliedUnder35 = +(100 / (100 - pred.prediction.over35.prob)).toFixed(2);

  const book = bookOdds?.markets || {};

  pred.markets.overUnder15 = {
    pick: pred.prediction.over15.pick,
    probability: pred.prediction.over15.prob,
    odds: book.overUnder15?.over || impliedOver15,
    oddsUnder: book.overUnder15?.under || impliedUnder15,
    source: book.overUnder15 ? 'bookmaker' : 'implied',
  };
  pred.markets.overUnder25 = {
    pick: pred.prediction.over25.pick,
    probability: pred.prediction.over25.prob,
    odds: book.overUnder25?.over || impliedOver25,
    oddsUnder: book.overUnder25?.under || impliedUnder25,
    source: book.overUnder25 ? 'bookmaker' : 'implied',
  };
  pred.markets.overUnder35 = {
    pick: pred.prediction.over35.pick,
    probability: pred.prediction.over35.prob,
    odds: book.overUnder35?.over || impliedOver35,
    oddsUnder: book.overUnder35?.under || impliedUnder35,
    source: book.overUnder35 ? 'bookmaker' : 'implied',
  };
  pred.markets.btts = {
    pick: pred.prediction.btts.pick,
    probability: pred.prediction.btts.prob,
    odds: book.btts?.yes || impliedBttsYes,
    oddsNo: book.btts?.no || impliedBttsNo,
    source: book.btts ? 'bookmaker' : 'implied',
  };
  pred.markets.highestHalf = pred.prediction.highestHalf;

  // Also top-level odds for the 1X2 row (though not primary market now)
  pred.odds = {
    ...pred.odds,
    home: book.h2h?.home || pred.odds.home,
    draw: book.h2h?.draw || pred.odds.draw,
    away: book.h2h?.away || pred.odds.away,
    over25: pred.markets.overUnder25.odds,
    bttsYes: pred.markets.btts.odds,
    source: book.h2h ? 'bookmaker' : 'bzzoiro_implied',
    bookmakerTitle: bookOdds?.bookmakerTitle || null,
  };

  pred.bookmaker = bookOdds ? {
    key: bookOdds.bookmaker,
    title: bookOdds.bookmakerTitle,
    lastUpdated: bookOdds.lastUpdated,
  } : null;

  logFeatureSnapshot(pred, features, 'over25', over25Prob).catch(() => {});
  logFeatureSnapshot(pred, features, 'btts', bttsYesProb).catch(() => {});
  logFeatureSnapshot(pred, features, 'over15', over15Prob).catch(() => {});

  ENRICH_CACHE.set(pred.eventId, { enrichedAt: Date.now(), pred: JSON.parse(JSON.stringify(pred)) });

  if (ENRICH_CACHE.size > 500) {
    const now = Date.now();
    for (const [k, v] of ENRICH_CACHE) {
      if (now - v.enrichedAt > ENRICH_TTL) ENRICH_CACHE.delete(k);
    }
  }

  return pred;
}

